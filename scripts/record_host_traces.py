"""Record REAL host request traces for the architecture viewer (docs/architecture/host-traces.js).

Runs a fixed set of scenarios against a live host (real Keycloak token, real Postgres RLS) and joins each response
with the host's own trace line, found by request id. Only measured facts are stored: HTTP status, the host's outcome
label, latency, role, and for search the returned document ids. Query text, tokens and record bodies are not stored.

Needs: KC_URL, KC_ADMIN_PASSWORD, HOST_URL and HOST_TRACE_FILE (the file the host writes; see HOST_TRACE_FILE).
Run from the repo root: `uv run python scripts/record_host_traces.py`
"""
from __future__ import annotations

import json
import os
import secrets
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx

from kc_dev_realm import USERS, admin_client, make_passwords, provision, token_for

HOST = os.environ["HOST_URL"].rstrip("/")
TRACE_FILE = Path(os.environ["HOST_TRACE_FILE"])
OUT = Path(__file__).resolve().parents[1] / "docs" / "architecture" / "host-traces.js"
STAFFING = "staffing plan hire support agents extend hours"  # shares vocabulary with the English staffing plan

# key, label, user, method, path, json body (search only), what the scenario shows
SCENARIOS = [
    ("own_order", "khách c001 tra đơn của mình", "alice", "GET", "/v1/orders/BM-1001", None),
    ("other_order", "khách c001 tra đơn của c002", "alice", "GET", "/v1/orders/BM-1002", None),
    ("missing_order", "khách c001 tra mã không tồn tại", "alice", "GET", "/v1/orders/BM-9999", None),
    ("finance_invoice", "tài chính xem hóa đơn", "fin", "GET", "/v1/invoices/INV-2026-0451", None),
    ("support_invoice", "hỗ trợ xem hóa đơn (không có quyền)", "sam", "GET", "/v1/invoices/INV-2026-0451", None),
    ("search_customer", "khách c001 tìm tài liệu nội bộ", "alice", "POST", "/v1/search", {"query": STAFFING, "top_k": 5}),
    ("search_manager", "quản lý tìm cùng câu đó", "mia", "POST", "/v1/search", {"query": STAFFING, "top_k": 5}),
    ("bad_token", "token sai chữ ký", None, "GET", "/v1/orders/BM-1001", None),
    ("no_token", "không có token", None, "GET", "/v1/orders/BM-1001", None),
]


def read_trace(request_id: str) -> dict | None:
    for _ in range(20):
        for line in reversed(TRACE_FILE.read_text(encoding="utf-8").splitlines()[-200:]):
            row = json.loads(line)
            if row.get("request_id") == request_id:
                return row
        time.sleep(0.1)
    return None


def build(key, label, user, method, path, body, token, run):
    request_id = f"viewer-{key.replace('_', '-')}-{run}"
    headers = {"x-request-id": request_id}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    r = httpx.request(method, HOST + path, headers=headers, json=body, timeout=20)
    row = read_trace(request_id)
    if row is None:
        raise SystemExit(f"no host trace line for {request_id}: is HOST_TRACE_FILE the file the host writes?")
    doc_ids = sorted({h["doc_id"] for h in r.json()["results"]}) if body and r.status_code == 200 else None
    role, cid = (USERS[user] if user else (None, None))
    return {
        "key": key, "label": label,
        "actor": {"user": user, "role": role, "customer_id": cid},
        "request": {"method": method, "path": path, "query_chars": len(body["query"]) if body else None},
        "response": {"status": r.status_code, "outcome": row["outcome"], "latency_ms": row["latency_ms"],
                     "request_id": request_id, "result_count": row.get("result_count"), "doc_ids": doc_ids},
        "trace_line": {k: row[k] for k in ("route", "status", "outcome", "actor_role", "actor", "kind", "ref", "top_k", "result_count") if k in row},
    }


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    passwords = make_passwords()
    with admin_client() as admin:
        provision(admin, passwords)
    tokens = {u: token_for("bepmay-web", u, passwords[u]) for u in USERS}
    run = secrets.token_hex(3)
    out = []
    for key, label, user, method, path, body in SCENARIOS:
        token = tokens[user] if user else ("x" + tokens["alice"][1:-4] + "AAAA" if key == "bad_token" else None)
        s = build(key, label, user, method, path, body, token, run)
        out.append(s)
        print(f"{key:16} -> {s['response']['status']} {s['response']['outcome']:18} {s['response']['latency_ms']} ms")
    payload = {
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": "Keycloak 26.8.2 (dev, loopback) · host API · PostgreSQL 16 + pgvector · RLS role không bypass · embedder hash (kiểm thử, không phải ngữ nghĩa)",
        "scenarios": out,
    }
    OUT.write_text(
        "// Generated by scripts/record_host_traces.py from real host requests. Do not edit by hand.\n"
        "window.HOST_TRACES = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
